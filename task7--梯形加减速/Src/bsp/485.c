static uint16_t Crc16Modbus(uint8_t *_pBuf, uint16_t _usLen)
{
	uint8_t ucCRCHi = 0xFF;
	uint8_t ucCRCLo = 0xFF;
	uint16_t usIndex;

	while (_usLen--)
	{
		usIndex = ucCRCHi ^ *_pBuf++;
		ucCRCHi = ucCRCLo ^ s_crchi[usIndex];
		ucCRCLo = s_crclo[usIndex];
	}
	return ((uint16_t)ucCRCHi << 8 | ucCRCLo);
}

// 485的初始化
void Rs485Init(void)
{
	Usart1Init();
}

// 485发送字符串
void Rs485UartWrite(char* String)
{
	uint8_t i = 0;

	// 485 设置为发送
	GPIO_SetBits(GPIOA, GPIO_Pin_12);
	vTaskDelay(3);

	for (i = 0; String[i] != '\0'; i++)
	{
		Serial1SendByte(String[i]);
	}

	vTaskDelay(3);
	// 485 设置为接收
	GPIO_ResetBits(GPIOA, GPIO_Pin_12);
}

// 使用485发送指令
void Rs485TxOpr(uint8_t uAddr, uint8_t opr, uint16_t uReg, uint16_t uData)
{
	uint8_t  tx_date[8];
	uint16_t crc;

	tx_date[0] = uAddr;
	tx_date[1] = opr;
	tx_date[2] = uReg >> 8;
	tx_date[3] = uReg;
	tx_date[4] = uData >> 8;
	tx_date[5] = uData;

	// CRC校验
	crc = Crc16Modbus(tx_date, 6);
	tx_date[6] = crc >> 8;
	tx_date[7] = crc & 0xFF;

	// 485 设置为发送
	GPIO_SetBits(GPIOA, GPIO_Pin_12);
	vTaskDelay(3);

	for (uint8_t i = 0; i < 8; i++)
	{
		Serial1SendByte(tx_date[i]);
	}

	vTaskDelay(3);
	// 485 设置为接收
	GPIO_ResetBits(GPIOA, GPIO_Pin_12);
}

// 485接收数据 + 校验
static uint32_t Rs485RxData(void)
{
	uint32_t result = 0;

	if (usart1_rx_finished)
	{
		usart1_rx_finished = 0;

		if (usart1_rx_count > 5)
		{
			// 校验CRC
			uint16_t crc_calc = Crc16Modbus((uint8_t*)usart1_rx_buffer, usart1_rx_count - 2);
			uint16_t crc_recv = (usart1_rx_buffer[usart1_rx_count - 2] << 8) | usart1_rx_buffer[usart1_rx_count - 1];

			if (crc_calc == crc_recv)
			{
				result = (usart1_rx_buffer[3] << 8) | usart1_rx_buffer[4];
			}
		}
		// 清空接收缓冲区
		memset((void*)usart1_rx_buffer, 0, usart1_rx_count);
		usart1_rx_count = 0;
	}
	return result;
}

// 获取温度值
uint32_t GetTempture(void)
{
	Rs485TxOpr(0x12, 0x03, 0x0102, 0x0001);
	vTaskDelay(100);

	if (usart1_rx_finished)
	{
		float temp = (float)Rs485RxData() / 10;
		return (uint32_t)temp;
	}
	else
	{
		return 0xFFFFFFFF;
	}
}

// 获取距离值
uint32_t GetDistance(void)
{
	Rs485TxOpr(0x12, 0x03, 0x0101, 0x0001);
	vTaskDelay(100);

	if (usart1_rx_finished)
	{
		float dis = (float)Rs485RxData();
		return (uint32_t)dis;
	}
	else
	{
		return 0xFFFFFFFF;
	}
}

// USART1中断接收处理函数
void USART1_IRQHandler(void)
{
	if (USART_GetITStatus(USART1, USART_IT_RXNE) != RESET)
	{
		uint8_t data = USART_ReceiveData(USART1);

		if (usart1_rx_index < 256)
		{
			usart1_rx_buffer[usart1_rx_index++] = data;
		}
		USART_ClearITPendingBit(USART1, USART_IT_RXNE);
	}

	if (USART_GetITStatus(USART1, USART_IT_IDLE) != RESET)
	{
		volatile uint16_t temp = USART1->SR;
		temp = USART1->DR;
		(void)temp;

		usart1_rx_count = usart1_rx_index;
		usart1_rx_finished = 1;
		usart1_rx_index = 0;
		USART_ClearITPendingBit(USART1, USART_IT_IDLE);
	}
}
